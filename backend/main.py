from .llm import ask_mimo, classify_intent
from .legacy_tools import execute_tool
from .memory import (
    initialize_memory,
    save_memory,
    get_memories,
    search_memory,
    forget_memory
)

conversation_history = []


def show_devices():
    from .core.security import get_service
    devices = get_service().store.list_devices()
    if not devices:
        print("No paired devices yet.")
    for d in devices:
        seen = d["last_seen"] or "never"
        print(f"[{d['id']}] {d['name']} ({d['kind']}) last seen: {seen}")
    return devices


def issue_pairing_code():
    """Print a one-time code for a new device. Run this on the PC that hosts the backend.

    The code must be generated by the running backend process, so this asks it over
    loopback - the same path the phone uses to redeem the code.
    """
    import os

    import requests

    base = os.environ.get("MIMO_BACKEND_URL", "http://127.0.0.1:8000").rstrip("/")
    try:
        response = requests.post(f"{base}/auth/pair/code", timeout=5)
        response.raise_for_status()
        code = response.json()["code"]
    except Exception:
        print(f"\nCould not reach the MIMO backend at {base}.")
        print("Start it first (uvicorn backend.api:app --host 127.0.0.1 --port 8000),")
        print("then run this command again.\n")
        return None
    print("\nMIMO pairing code:  " + code)
    print("Valid for 10 minutes, single use.")
    print("On the new device: Settings -> Connect -> type the code.\n")
    return code


def run_chat():
    global conversation_history
    print("MIMO Agent is starting...")
    print("Type 'exit' to stop.")
    print("Type 'memories' to inspect stored memories.")

    while True:
        command = input("\nYou: ").strip()

        if not command:
            continue

        if command.lower() in ["exit", "quit"]:
            print("\nMIMO: See you again.")
            break

        if command.lower() == "memories":
            memories = get_memories()

            if memories:
                print("\nMIMO Memory Database:")

                for memory in memories:
                    print(
                        f"[{memory['id']}] "
                        f"[{memory['category']}] "
                        f"{memory['content']}"
                    )
            else:
                print("\nMIMO: No memories stored.")

            continue

        try:
            classification = classify_intent(command)

            intent = classification.get("intent")
            parameters = classification.get("parameters", {})

            if intent in [
                "get_time",
                "get_date",
                "calculate",
                "open_website",
                "open_app"
            ]:
                result = execute_tool(intent, parameters)
                response = str(result["result"])

            elif intent == "save_memory":
                content = parameters.get("content")
                category = parameters.get("category", "other")

                if isinstance(content, str) and content.strip():
                    saved = save_memory(content, category)

                    response = (
                        "I'll remember that."
                        if saved
                        else "I already have that memory stored."
                    )
                else:
                    response = "Please tell me what to remember."

            elif intent == "search_memory":
                keyword = parameters.get("keyword", "")
                lower_command = command.lower()

                category_rules = {
                    "interest": ["interest", "interests"],
                    "skill": ["skill", "skills", "learning"],
                    "goal": ["goal", "goals", "ambition", "ambitions"],
                    "project": ["project", "projects"],
                    "preference": ["preference", "preferences"],
                    "education": ["education", "academic"]
                }

                category = parameters.get("category")

                for category_name, keywords in category_rules.items():
                    if any(word in lower_command for word in keywords):
                        category = category_name
                        break

                memories = search_memory(keyword, category)

                if memories:
                    response = "Here's what I remember:\n"
                    response += "\n".join(
                        f"- [{memory['category']}] {memory['content']}"
                        for memory in memories
                    )
                else:
                    response = "I couldn't find a matching memory."

            elif intent == "forget_memory":
                keyword = parameters.get("keyword", "")

                if keyword:
                    count = forget_memory(keyword)
                    response = f"Forgot {count} matching memories."
                else:
                    response = "Please specify what to forget."

            elif intent == "general_question":
                memories = get_memories()

                response = ask_mimo(
                    command,
                    memories=memories,
                    history=conversation_history
                )

            else:
                response = "I cannot handle that request yet."

            print("\nMIMO:", response)

            conversation_history.append({
                "role": "user",
                "content": command
            })

            conversation_history.append({
                "role": "assistant",
                "content": response
            })

            conversation_history = conversation_history[-10:]

        except Exception as error:
            print("\nMIMO: Something went wrong:", error)


def main(argv=None):
    import sys
    args = list(sys.argv[1:] if argv is None else argv)
    initialize_memory()
    if args and args[0] == "pair":
        issue_pairing_code()
        return 0
    if args and args[0] == "devices":
        show_devices()
        return 0
    run_chat()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
